// Writes src/project_files.js (run by render.mjs, engine/sync.mjs and `bin/t2mv timeline`; run it by hand before opening
// studio.html after adding project files):
//   window.ASSET_LIST      every image in assets/ (riso photo prints etc.)
//   window.PROJECT_SCRIPTS the project-owned scripts, loaded AFTER the engine (core, frame, cast, props) in this order:
//     src/msg_data.js       per-day sent counts for the odometer (tools/msgcounts.mjs)
//     src/cast_project.js   project cast: re-skins, new outfits, new people (CAST.CHAR / CAST.OUT / CAST.ME_AGE + castMember)
//     src/props_project.js  project sets and props (new globals; may wrap or replace engine ones)
//     src/hud.js            project HUD: HUD.* config, or redefine frame.js HUD functions
//     src/story.js          HUD.birthday / HUD.label + storyKeys([...]) story dates (the director's file)
//     src/ch/*.js           chapters, by name
// Missing files are skipped.
import { readdirSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
const list = existsSync('assets') ? readdirSync('assets').filter(f => /\.(png|jpe?g|webp)$/i.test(f)).sort() : [];
const scripts = ['src/msg_data.js', 'src/cast_project.js', 'src/props_project.js', 'src/hud.js', 'src/story.js'].filter(f => existsSync(f));
if (existsSync('src/ch')) scripts.push(...readdirSync('src/ch').filter(f => f.endsWith('.js')).sort().map(f => 'src/ch/' + f));
mkdirSync('src', { recursive: true });
writeFileSync('src/project_files.js', `// generated by tools/assets.mjs — do not edit\nwindow.ASSET_LIST = ${JSON.stringify(list)};\nwindow.PROJECT_SCRIPTS = ${JSON.stringify(scripts)};\n`);
