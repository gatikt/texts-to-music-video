"""Hand-compute the demo's timing files from the synthetic beat grid (no audio analysis needed).
The song (make_song.sh) is exactly 120 BPM from t=0: a beat every 0.5 s, a bar every 2 s, 30 s long.
Each lyric line takes one bar starting at bar 1 (t = 2.0 s); its words land on eighth notes (0.25 s apart).
Writes, next to this script:  beats.json  aligned.json  chapters.json  build/src/timeline_data.js
(the same shapes scripts/analyze_audio.py, scripts/align_lyrics.py and scripts/make_timeline.py produce).
usage: python3 make_timing.py"""
import json, os
os.chdir(os.path.dirname(os.path.abspath(__file__)))
DUR, BPM, BEAT, BAR, FIRST = 30.0, 120.0, 0.5, 2.0, 2.0
beats = [round(i * BEAT, 3) for i in range(int(DUR / BEAT))]
json.dump({'tempo': BPM, 'beats': beats}, open('beats.json', 'w'))
lines, sec = [], None
for raw in open('lyrics.txt').read().splitlines():
    l = raw.strip()
    if not l: continue
    if l.startswith('[') and l.endswith(']'): sec = l[1:-1]; continue
    lines.append((sec, l))
out = []
for i, (sec, text) in enumerate(lines):
    s0 = FIRST + i * BAR
    ws = text.split(); step = 0.25 if len(ws) <= 7 else 1.75 / len(ws)
    words = [{'w': w, 's': round(s0 + k * step, 3)} for k, w in enumerate(ws)]
    out.append({'i': i, 'sec': sec, 'who': None, 's': s0, 'text': text, 'words': words, 'e': round(s0 + 1.95, 3)})
json.dump(out, open('aligned.json', 'w'), indent=0)
chapters = [['c01_verse1', 0, 10.0], ['c02_chorus', 10.0, 18.0], ['c03_verse2', 18.0, DUR]]
json.dump(chapters, open('chapters.json', 'w'))
TL = {'duration': DUR, 'bpm': BPM, 'beats': beats, 'lines': out, 'meter': [[0, 0], [DUR, 100]],
      'out': 'demo', 'audio': '../song_cut.wav', 'title': 'Group Chat at 2 A.M. (demo)'}
os.makedirs('build/src', exist_ok=True)
open('build/src/timeline_data.js', 'w').write('// generated by make_timing.py: beats on the synthetic 120 BPM grid, words on eighth notes\nconst TL = ' + json.dumps(TL, separators=(',', ':')) + ';\n')
open('build/chapters.json', 'w').write(json.dumps(chapters))
for o in out: print(f"{o['i']:3d} {o['s']:6.2f}-{o['e']:6.2f} {str(o['sec'])[:14]:14s} {o['text']}")
