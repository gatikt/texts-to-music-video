"""Wire a song's timing into a project's build/ folder. Writes PROJECT-OWNED files only; the engine-owned files
(render.mjs, studio.html, src/core.js, src/frame.js, src/cast.js, src/props.js, ...) are copied in by engine/sync.mjs
and are never edited here.

usage: python3 scripts/make_timeline.py <video_dir> <duration_s> <out_name.mp4> <chapters.json> [--build DIR] [--start-date YYYY-MM-DD]
  video_dir has beats.json and aligned.json (bin/t2mv audio) and build/ (bin/t2mv timeline creates it).
  chapters.json = [["c01_intro", 0, 24.8], ["c02_verse1", 24.8, 40.48], ...]  (cut on section starts from aligned.json)

Writes:
  build/src/timeline_data.js   TL = {duration, bpm, beats, lines, meter, out, audio}  (always rewritten)
  build/chapters.json          the chapter list
  build/src/ch/<name>.js       an empty placeholder per chapter (only if missing)
  build/src/story.js           a starter story file (only if missing): HUD.birthday = null and, with --start-date, one
                               storyKeys([[0, '<start-date>']]) key. The pre-production director fills in the real dates.
Then run `node tools/assets.mjs` in build/ (bin/t2mv timeline does) so studio.html lists the chapters."""
import json, re, os, argparse, datetime

ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument('video_dir'); ap.add_argument('duration', type=float); ap.add_argument('out_name'); ap.add_argument('chapters_json')
ap.add_argument('--build', help='build dir (default <video_dir>/build)')
ap.add_argument('--start-date', default=None, help="first story date for the starter src/story.js, YYYY-MM-DD (project.json story_start_date)")
ap.add_argument('--audio', default='../song_cut.wav', help='audio path for the encode, relative to build/ (default ../song_cut.wav)')
A = ap.parse_args()
if A.start_date:
    try: datetime.date.fromisoformat(A.start_date)
    except ValueError: ap.error(f'--start-date must be YYYY-MM-DD, got {A.start_date!r}')

V, DUR, OUTNAME = A.video_dir, A.duration, A.out_name
CH = json.load(open(A.chapters_json))
B = A.build or os.path.join(V, 'build')
os.makedirs(os.path.join(B, 'src', 'ch'), exist_ok=True)
a = json.load(open(os.path.join(V, 'aligned.json'))); b = json.load(open(os.path.join(V, 'beats.json')))

TL = {'duration': DUR, 'bpm': round(b['tempo'], 2), 'beats': b['beats'], 'lines': a, 'meter': [[0, 0], [DUR, 100]],
      'out': re.sub(r'\.mp4$', '', OUTNAME), 'audio': A.audio}
with open(os.path.join(B, 'src', 'timeline_data.js'), 'w') as f:
    f.write('// generated by scripts/make_timeline.py: beats from librosa, word times from faster-whisper aligned to lyrics (as sung)\n'
            'const TL = ' + json.dumps(TL, separators=(',', ':')) + ';\n')

made = 0
for n, s0, e0 in CH:
    p = os.path.join(B, 'src', 'ch', f'{n}.js')
    if not os.path.exists(p):
        open(p, 'w').write(f'// {n} — {s0} → {e0} (placeholder, owned by its chapter agent)\n'); made += 1
json.dump(CH, open(os.path.join(B, 'chapters.json'), 'w'))

story = os.path.join(B, 'src', 'story.js')
new_story = not os.path.exists(story)
if new_story:
    key = f"storyKeys([\n  [0, '{A.start_date}'],\n]);" if A.start_date else \
          "// storyKeys([\n//   [0, 'YYYY-MM-DD', 'H:MM AM', { label: 'HOME' }],\n// ]);"
    open(story, 'w').write(
        "// story.js — project-owned HUD config + story dates (the pre-production director's file). Loaded after the engine,\n"
        "// before the chapters. Every date/time must be the REAL timestamp of the message on screen. Format: see STORY_DATES in\n"
        "// src/frame.js: [songTime, 'YYYY-MM-DD', 'H:MM AM' | null, {label, roll, age}].\n"
        "HUD.birthday = null;           // [YYYY, M, D] turns on the auto 'AGE n' line under the date\n"
        "HUD.label = 'MSGS SENT';\n" + key + "\n")
print(f'ok {len(CH)} chapters ({made} new placeholder(s)), duration {DUR}' + ('; wrote a starter src/story.js' if new_story else '; kept src/story.js'))
