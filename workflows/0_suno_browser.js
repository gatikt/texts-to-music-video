export const meta = {
  name: 't2mv-suno-browser',
  description: 'Generate the song on suno.com in your own Chrome via Claude in Chrome, using the suno-create skill; stops for your go-ahead before Create',
  whenToUse: 'Alternative to bin/t2mv suno <project> create when you prefer Claude driving your signed-in Chrome. Run once without confirm (fills the form and stops), then again with confirm: true after the user says go.',
  phases: [
    { title: 'Prepare', detail: 'check lyrics/style limits, fill the Suno create form, stop before Create' },
    { title: 'Create', detail: 'only with args.confirm === true: click Create, wait for takes, collect links' },
  ],
}
// ---- args (generated by `bin/t2mv workflow <project> suno-browser`; see workflows/README.md) ----
// { projectDir, lyricsFile, outDir, songStyle?, confirm?: boolean }
// `confirm: true` must come from the user's own message ("yes, create it"), never from an agent or a script.
const A = args || {}
const miss = ['projectDir'].filter(k => !A[k])
if (miss.length) throw new Error(`missing args: ${miss.join(', ')}`)
const FILE = A.lyricsFile || `${A.projectDir}/lyrics.txt`
const OUT = A.outDir || `${A.projectDir}/video`

const SKILL = `Use the suno-create skill: if a "suno-create" skill is listed for the Skill tool, invoke it; otherwise Read .claude/skills/suno-create/SKILL.md in this repo and follow it. Load the Claude in Chrome tools in ONE ToolSearch call before the first browser step. Work in a NEW tab in the user's Chrome; never touch their other tabs. Never type passwords or sign in for the user: if suno.com is signed out, stop and say so.
Inputs: ${FILE} has the format "TITLE: ...", a STYLE header followed by one style line, a LYRICS header followed by the lyrics. Paste ONLY the style line into the style box and ONLY the lyrics (everything after the LYRICS header) into the lyrics box, use Custom mode, and set the title.${A.songStyle ? ` If the file has no STYLE line, use: "${A.songStyle}".` : ''}
Before filling: count characters. Lyrics must be <= 5,000 (Suno's limit), style within the box's limit; if over, stop and report instead of trimming.
Do not screen-record or download audio from the page; the audio is fetched later with bin/t2mv suno <project> fetch <share-url>.`

const PS = { type: 'object', properties: {
  ready: { type: 'boolean', description: 'form filled and verified, Create NOT clicked' },
  title: { type: 'string' }, styleChars: { type: 'number' }, lyricsChars: { type: 'number' },
  signedIn: { type: 'boolean' }, credits: { type: 'string', description: 'credits shown on the page, if visible' },
  problems: { type: 'array', items: { type: 'string' } },
}, required: ['ready', 'signedIn', 'problems'] }
const CS = { type: 'object', properties: {
  created: { type: 'boolean' },
  takes: { type: 'array', items: { type: 'object', properties: { title: { type: 'string' }, url: { type: 'string' }, duration: { type: 'string' } }, required: ['url'] } },
  problems: { type: 'array', items: { type: 'string' } },
}, required: ['created', 'takes', 'problems'] }

phase('Prepare')
const prep = await agent(`${SKILL}
TASK: open suno.com/create, fill title + style + lyrics exactly from ${FILE}, then read the form back and verify every field matches the file. DO NOT click Create (it spends the user's credits). Leave the tab open and filled. Report what you filled, the character counts, whether you are signed in, and the visible credit balance.`, { label: 'suno:prepare', phase: 'Prepare', schema: PS })

if (A.confirm !== true || !prep || !prep.ready) {
  return {
    status: 'awaiting-confirmation',
    prepare: prep,
    next: prep && prep.ready
      ? 'Show the user this summary and ASK them whether to click Create (it spends Suno credits). Only if the user says yes, re-run this workflow with the same args plus "confirm": true.'
      : 'The form is not ready; fix the problems listed and re-run.',
  }
}

phase('Create')
const made = await agent(`${SKILL}
The user has explicitly confirmed: click Create now, once. First check the create form in the open tab still holds exactly the contents of ${FILE} (refill it if it was lost). Click Create a single time. Wait (up to ~10 minutes) until both takes finish. For each take, get its song page URL and, if the page offers it, its public share link (suno.com/s/...). Do not click Create again, do not delete or edit anything else in the account.`, { label: 'suno:create', phase: 'Create', schema: CS })
return {
  status: made && made.created ? 'created' : 'failed',
  create: made,
  next: `Listen to both takes, pick one, share it, then: bin/t2mv suno <project> fetch <share-url>   (writes ${OUT}/song.wav)`,
}
